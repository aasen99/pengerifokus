function spennShoppingOffer(
  id: string,
  partner: string,
  offerLabel: string,
  description: string,
  category: string,
  options?: { terms?: string; warning?: string },
): Tilbud {
  return {
    id: `tilbud-spenn-${id}`,
    slug: `spenn-${id}`,
    status: "published",
    title: partner,
    description,
    offerLabel,
    partner,
    fordelSlug: "spenn",
    category,
    terms: options?.terms ?? spennOnlineShoppingBase,
    sourceUrl: spennSourceUrl,
    warning: options?.warning,
    createdAt: "2026-08-18",
    updatedAt: spennCheckedAt,
  };
}

